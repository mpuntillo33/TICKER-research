"""Write outputs/report.md and outputs/visible_output.json from the engine. Run from the repo root:
    python tools/make_report.py
Every number in the report is computed here from analysis.py and comps.py; nothing is typed in.
"""
import json
import sys
from dataclasses import replace
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import analysis as A  # noqa: E402
import comps as C  # noqa: E402


# Alternative ranges: the two top drivers get narrow, "management-credible" bands; others keep full bands.
NARROW = {"sga_to_gp_long": (0.925, 0.935), "wacc": (0.072, 0.082), "terminal_growth": (0.015, 0.025)}


def ranking(override: dict | None = None) -> list[tuple[str, float]]:
    """Swing in value/share when each driver moves across its band (or an override band), all else at base."""
    out = []
    for k, (_, _, lo, hi, *_r) in A.BOUNDS.items():
        lo, hi = (override or {}).get(k, (lo, hi))
        vals = [A.value(replace(A.BASE, **{k: x})) for x in (lo, hi)]
        out.append((k, abs(vals[1] - vals[0])))
    return sorted(out, key=lambda r: r[1], reverse=True)


def fmt_table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---:" if i else "---" for i in range(len(header))) + "|\n"
    return s + "".join("| " + " | ".join(r) + " |\n" for r in rows)


def main():
    r = A.run()
    s, v = r["statements"], r["valuation"]
    price = A.MARKET["price"]
    cases = A.cases()
    rev = A.reverse_dcf(price)
    wb = A.wacc_build()
    comp = C.results()
    fcfe = A.fcfe_value(s)
    yrs = [f"FY{y}E" for y in A.YEARS]
    md = []
    md.append("# ACI Project 1 — Frozen Visible Output\n")
    md.append("Generated by `python tools/make_report.py` from `analysis.py` and `comps.py`. USD millions except per share.\n")
    md.append(f"- **Decision:** initiate / watch-defer / do not initiate Albertsons (NYSE: ACI); user: fund investment committee, no position.\n"
              f"- **Valuation (bridge) date:** Sept 12, 2026 (Q2 FY2026). **Price:** ${price:.2f}, close {A.MARKET['price_date']}.\n"
              f"- **Share basis:** {A.FILING['diluted_shares']}m diluted weighted-average Class A shares (Q2 FY2026, Form 8-K filed Oct 13, 2026).\n"
              f"- **Filings:** FY2025 10-K (filed Apr 27, 2026); Q1 FY2026 10-Q (filed Jul 28, 2026); Q2 FY2026 earnings release 8-K (filed Oct 13, 2026).\n")
    md.append("## Valuation summary\n")
    md.append(fmt_table(["Case", "Value per share"], [[k, f"${x:.2f}"] for k, x in cases.items()]))
    md.append(f"\nMarket price ${price:.2f}. Base DCF / price = {cases['Base'] / price:.2f}x. "
              f"Terminal value = {v['terminal_share']:.1%} of EV.\n\n"
              f"**Reverse DCF:** holding every other driver at base, the price implies a long-run (FY2030) SG&A / gross profit of "
              f"**{rev:.2%}**, versus {A.BASE.sga_to_gp_fy2026:.1%} in FY2026E and a base of {A.BASE.sga_to_gp_long:.1%}. "
              f"The market is pricing roughly no cost recovery.\n")
    md.append("## Enterprise-to-equity bridge (Sept 12, 2026)\n")
    md.append(fmt_table(["Item", "$m"], [
        ["PV of explicit FCFF (stub FY2026 + FY2027–FY2030)", f"{v['pv_explicit']:,.1f}"],
        ["PV of terminal value", f"{v['pv_terminal']:,.1f}"],
        ["Enterprise value", f"{v['enterprise_value']:,.1f}"],
        ["Less: debt incl. finance leases", f"({v['debt']:,.1f})"],
        ["Less: opioid settlement obligation (10-K Note 12)", f"({v['other_debt_like']:,.1f})"],
        ["Add: cash and equivalents", f"{v['cash']:,.1f}"],
        ["Equity value", f"{v['equity_value']:,.1f}"],
        ["÷ diluted shares (m)", f"{v['shares']:.1f}"],
        ["Value per share", f"${v['value_per_share']:.2f}"]]))
    md.append("\n## WACC build\n")
    md.append(fmt_table(["Input", "Value", "Source / as-of"], [
        ["Risk-free (10-yr Treasury)", f"{A.WACC_INPUTS['risk_free']:.2%}", "FRED DGS10, Oct 15, 2026"],
        ["Equity risk premium", f"{A.WACC_INPUTS['erp']:.2%}", "Damodaran implied ERP (as used in Lab 06, Sep 2026)"],
        ["Unlevered beta", f"{A.WACC_INPUTS['unlevered_beta']:.2f}", "Damodaran Retail (Grocery and Food), cash-corrected, Jan 2026"],
        ["Market D/E (debt incl. finance leases / market cap)", f"{wb['d_to_e']:.2f}", "$9,328.2m / ($13.09 × 485.3m)"],
        ["Levered beta", f"{wb['levered_beta']:.2f}", "Hamada relevering, 25.5% tax"],
        ["Cost of equity", f"{wb['cost_of_equity']:.2%}", "CAPM"],
        ["After-tax cost of debt", f"{wb['after_tax_cost_of_debt']:.2%}", "5.9% pretax (interest / debt)"],
        ["Equity weight", f"{wb['equity_weight']:.1%}", "market values"],
        ["WACC (computed → used)", f"{wb['wacc']:.2%} → {A.BASE.wacc:.1%}", "rounded"],
        ["Rejected: provider raw beta", f"{A.WACC_INPUTS['raw_regression_beta_rejected']:.2f}", "2022–24 merger-arbitrage pricing distorts it"]]))
    md.append("\n## Pro-forma statements (base case)\n")
    lines = [("Revenue", "revenue"), ("Gross profit", "gross_profit"), ("SG&A", "sga"), ("EBITDA", "ebitda"),
             ("EBIT", "ebit"), ("Interest", "interest"), ("Net income", "net_income"),
             ("Inventory", "inventory"), ("Accounts payable", "accounts_payable"), ("PP&E", "ppe"),
             ("Cash", "cash"), ("Debt", "debt"), ("Equity", "equity"), ("Total assets", "total_assets"),
             ("Balance-sheet gap", "bs_gap"), ("Cash from operations", "cfo"), ("Cash from investing", "cfi"),
             ("Cash from financing", "cff"), ("Net change in cash", "net_change_in_cash"),
             ("NOPAT", "nopat"), ("D&A", "da"), ("Capex", "capex"), ("Δ NWC", "delta_nwc"), ("FCFF", "fcff"), ("FCFE", "fcfe")]
    md.append(fmt_table(["$m"] + yrs, [[lab] + [f"{s[y][k]:,.1f}" for y in A.YEARS] for lab, k in lines]))
    md.append("\n## WACC × terminal growth (value per share)\n")
    grid = A.wacc_growth_grid()
    gs = list(next(iter(grid.values())).keys())
    md.append(fmt_table(["WACC \\ g"] + [f"{g:.1%}" for g in gs],
                        [[f"{w:.1%}"] + [f"${grid[w][g]:.2f}" for g in gs] for w in grid]))
    md.append("\n## One-at-a-time sensitivity (each driver across its historical band, all else at base)\n")
    md.append(fmt_table(["Driver", "Band", "Value at low", "Value at high", "Swing"],
                        [[t["driver"], f"{t['low']:.4g} to {t['high']:.4g}", f"${t['at_low']['value_per_share']:.2f}",
                          f"${t['at_high']['value_per_share']:.2f}", f"${t['swing']:.2f}"] for t in A.tornado()]))
    full, half = ranking(), ranking(NARROW)
    md.append("\n**Does the ranking depend on the ranges?** Re-run with narrow bands for the top three drivers "
              "(FY2030 SG&A/GP 92.5–93.5%, WACC 7.2–8.2%, terminal growth 1.5–2.5%); all other bands unchanged:\n\n")
    md.append(fmt_table(["Rank", "Historical bands", "Narrow bands for top three"],
                        [[str(i + 1), f"{a[0]} (${a[1]:.2f})", f"{b[0]} (${b[1]:.2f})"] for i, (a, b) in enumerate(zip(full, half))]))
    md.append(f"\nWith narrow bands the leader becomes **{half[0][0]}**, versus **{full[0][0]}** on historical bands: "
              "the ranking depends on how wide a range the committee believes, so it is reported as range-conditional, "
              "not as a probability claim.\n")
    md.append("\n## Comparable companies (one definition for all; stockanalysis.com / S&P Global, retrieved Oct 19, 2026)\n")
    md.append(fmt_table(["Ticker", "Role", "EV ($m)", "EBITDA TTM ($m)", "EV/EBITDA", "Balance sheet"],
                        [[t, c["role"], f"{C.ev(c):,.0f}", f"{c['ebitda_ttm']:,.0f}", f"{comp['multiples'][t]:.2f}x", c["bs_date"]]
                         for t, c in C.COMPANIES.items()]))
    md.append(f"\nEV = market cap + debt excluding all lease liabilities − cash (EBITDA is after rent). Implied ACI value from peer "
              f"EV/EBITDA: **${comp['implied_low']:.2f}–${comp['implied_high']:.2f}** (median ${comp['implied_median']:.2f}). "
              f"P/E (Lab 08, Sept 10, 2026, GAAP diluted EPS): **$5.44–$14.77** (median $10.11).\n")
    md.append("\n## Methods side by side (not averaged)\n")
    md.append(fmt_table(["Method", "Value per share", "Why it differs"], [
        ["FCFF DCF from pro-forma (primary)", f"${cases['Low: comps stay negative, margin slips']:.2f} / ${cases['Base']:.2f} / ${cases['High: turnaround works by FY2028']:.2f}",
         "Forward, normalized; most sensitive to long-run SG&A / gross profit and WACC"],
        ["FCFE pro-forma cross-check", f"${fcfe:.2f}", "Equity cash flows at a 10% cost of equity from the FY2025 balance sheet; no opioid bridge; date differs"],
        ["Peer EV/EBITDA", f"${comp['implied_low']:.2f}–${comp['implied_high']:.2f}", "Trailing EBITDA of a business whose EBITDA is falling; peers' EBITDA is stable; leverage turns each 1.0x multiple gap into ≈$7/share"],
        ["Peer P/E", "$5.44–$14.77", "FY2025 GAAP EPS of $0.40 is depressed by the $773.8m opioid charge; Kroger's EPS by impairments"],
        ["Market", f"${price:.2f}", f"Implies long-run SG&A / gross profit ≈ {rev:.1%}: no cost recovery"]]))
    md.append("\n## Checks\n")
    md.append(fmt_table(["Check", "Result", "Detail"],
                        [[n, "PASS" if ok else "**FAIL**", x] for n, ok, x in r["checks"] + A.base_year_reconciliation() + C.consistency_checks()]))
    (ROOT / "outputs").mkdir(exist_ok=True)
    (ROOT / "outputs" / "report.md").write_text("".join(x if x.endswith("\n") else x + "\n" for x in md), encoding="utf-8")
    summ = A.summary()
    summ["comps"] = {"ev_ebitda": comp["multiples"], "implied_range": [comp["implied_low"], comp["implied_high"]],
                     "pe_lab08_range": [5.44, 14.77]}
    summ["sensitivity_ranking_full_vs_half_bands"] = {"full": full, "half": half}
    (ROOT / "outputs" / "visible_output.json").write_text(json.dumps(summ, indent=2, default=float), encoding="utf-8")
    print("Wrote outputs/report.md and outputs/visible_output.json")


if __name__ == "__main__":
    main()
